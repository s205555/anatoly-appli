const TEXTES = { fr: typo, en: (s) => s };
const appliquer = (o, f) => {
  if (typeof o === 'string') return f(o);
  if (typeof o === 'function') return (...a) => f(o(...a));
  if (Array.isArray(o)) return o.map((v) => appliquer(v, f));
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, appliquer(v, f)]));
  return o;
};
const LANGUES = { fr: appliquer(fr, TEXTES.fr), en: appliquer(en, TEXTES.en) };

