const profond = (o) => {
  if (typeof o === 'string') return typo(o);
  if (typeof o === 'function') return (...a) => profond(o(...a));
  if (Array.isArray(o)) return o.map(profond);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, profond(v)]));
  return o;
};

